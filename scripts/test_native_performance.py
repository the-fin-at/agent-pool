"""Opt-in cached SSH and real macOS WKWebView/Rust-IPC performance acceptance.

Reads a named connection. Production receives only cached status requests. All
delay injection and native UI state use private disposable test directories.
"""
import argparse
import contextlib
import hashlib
import json
import math
import os
from pathlib import Path
import platform
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import time
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[1]
SSH_OPTIONS = ['-T', '-o', 'BatchMode=yes', '-o', 'StrictHostKeyChecking=yes',
               '-o', 'ForwardAgent=no', '-o', 'ConnectTimeout=10']


def run(argv, *, stdin=None, env=None, timeout=30):
    result = subprocess.run(argv, input=stdin, capture_output=True, text=True,
                            env=env, timeout=timeout)
    if result.returncode:
        # Never echo remote status, account metadata, command arguments or logs.
        raise RuntimeError(f'{Path(argv[0]).name} exited {result.returncode}')
    return result.stdout


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def summary(samples):
    ordered = sorted(samples)
    if not ordered:
        raise ValueError('A timing distribution cannot be empty')
    return {'count':len(ordered), 'p95_ms':ordered[math.ceil(.95 * len(ordered)) - 1],
            'max_ms':ordered[-1], 'median_ms':ordered[(len(ordered) - 1) // 2]}


def ssh(host, argv, *, stdin=None, timeout=30):
    executable = shutil.which('ssh')
    if not executable:
        raise RuntimeError('OpenSSH client is required')
    return run([executable, *SSH_OPTIONS, host, shlex.join(argv)],
               stdin=stdin, timeout=timeout)


def connection(cli, name):
    value = json.loads(run([str(cli), 'remote', 'list']))[name]
    if set(value) != {'host', 'command', 'home'}:
        raise ValueError('Unexpected connection configuration')
    if not re.fullmatch(r'[A-Za-z0-9_][A-Za-z0-9_.@:\[\]-]{0,254}', value['host']):
        raise ValueError('Use a configured SSH alias without options')
    if not value['home'].startswith('/') or not value['command']:
        raise ValueError('Connection must name an executable and absolute server pool')
    if any(ord(char) < 32 for item in value.values() for char in item):
        raise ValueError('Control characters are not allowed in connection metadata')
    return value


def add_connection(cli, local_home, name, config):
    run([str(cli), '--home', str(local_home), 'remote', 'add', name,
         '--host', config['host'], '--command', config['command'],
         '--server-home', config['home']])


def cached_status(cli, local_home, name, samples):
    timings = []
    versions = set()
    response_bytes = []
    pending_jobs = []
    account_counts = []
    workers_online = []
    for _ in range(samples):
        started = time.perf_counter()
        raw = run([str(cli), '--home', str(local_home), '--remote', name, 'status'], timeout=15)
        timings.append((time.perf_counter() - started) * 1000)
        status = json.loads(raw)
        versions.add(status['version'])
        if not isinstance(status.get('accounts'), list):
            raise RuntimeError('Cached status did not return account metadata')
        response_bytes.append(len(raw.encode()))
        pending_jobs.append(status.get('pending_jobs'))
        account_counts.append(len(status['accounts']))
        workers_online.append(status.get('worker', {}).get('online'))
    measured = summary(timings)
    return {'passed':measured['p95_ms'] < 3000, 'budget_p95_ms':3000,
            'quantile':'nearest-rank ceil(.95*n)', 'warmup_excluded':False,
            'samples_ms':timings, **measured, 'server_versions':sorted(versions),
            'response_bytes':response_bytes, 'provider_inference':False,
            'pending_jobs':pending_jobs, 'account_counts':account_counts,
            'workers_online':workers_online,
            'request':'cached status; no refresh'}


@contextlib.contextmanager
def delayed_endpoint(config, seconds):
    parent = str(Path(config['home']).parent/'agent-fleet-validation')
    # The directory is private and generated by mktemp; never clean a supplied path.
    folder = ssh(config['host'], ['python3', '-c',
        'import os,pathlib,tempfile,sys; p=pathlib.Path(sys.argv[1]); p.mkdir(mode=0o700,parents=True,exist_ok=True); '
        'print(tempfile.mkdtemp(prefix="native-performance.",dir=p))', parent]).strip()
    expected_parent = Path(parent)
    if Path(folder).parent != expected_parent or not Path(folder).name.startswith('native-performance.'):
        raise RuntimeError('Unexpected disposable remote directory')
    wrapper = str(Path(folder)/'delayed-rpc')
    source = '''#!/usr/bin/env python3
import json,os,pathlib,subprocess,sys,time
ROOT=pathlib.Path(__file__).resolve().parent
env=os.environ.copy()
env.update(HOME=str(ROOT/'empty-home'),CODEX_HOME=str(ROOT/'empty-codex'),CLAUDE_CONFIG_DIR=str(ROOT/'empty-claude'))
started=time.monotonic()
reply=subprocess.run([COMMAND,*sys.argv[1:]],input=sys.stdin.buffer.read(),capture_output=True,env=env,timeout=15)
delay_started=time.monotonic()
time.sleep(DELAY)
delay=time.monotonic()-delay_started
with (ROOT/'timings.jsonl').open('a') as log: log.write(json.dumps({'native_ms':(delay_started-started)*1000,'delay_ms':delay*1000,'returncode':reply.returncode})+'\\n')
sys.stdout.buffer.write(reply.stdout);sys.stderr.buffer.write(reply.stderr);sys.exit(reply.returncode)
'''.replace('COMMAND', repr(config['command'])).replace('DELAY', repr(seconds))
    try:
        ssh(config['host'], ['python3', '-c',
            'import pathlib,sys; p=pathlib.Path(sys.argv[1]); p.write_text(sys.stdin.read()); p.chmod(0o700)',
            wrapper], stdin=source)
        yield {'host':config['host'], 'command':wrapper, 'home':str(Path(folder)/'pool')}, folder
    finally:
        # Only the path returned by this invocation's mktemp is eligible for removal.
        ssh(config['host'], ['python3', '-c',
            'import pathlib,shutil,sys; p=pathlib.Path(sys.argv[1]); parent=pathlib.Path(sys.argv[2]); '
            'assert p.parent==parent and p.name.startswith("native-performance."); shutil.rmtree(p)',
            folder, parent])


def native_ui(desktop, local_home, output, delay_seconds, version):
    if sys.platform != 'darwin':
        return {'passed':False, 'unavailable':'native macOS WKWebView requires macOS'}, 77
    session = json.loads(run(['/usr/bin/swift', str(ROOT/'scripts/macos_gui_state.swift')], timeout=20))
    if session['screen_locked'] or not session['console_session']:
        return {'passed':False, 'unavailable':'macOS locked or not on console', **session}, 77
    if b'AGENT_FLEET_TEST_SCRIPT' not in desktop.read_bytes():
        raise ValueError('Select a debug desktop with the native test hook, not a release binary')
    running = subprocess.run(['/bin/ps', '-axo', 'pid=,command='], capture_output=True, text=True, check=True).stdout
    for line in running.splitlines():
        fields = line.strip().split(maxsplit=1)
        if len(fields) != 2 or int(fields[0]) in {os.getpid(), os.getppid()}:
            continue
        with contextlib.suppress(ValueError):
            tokens = shlex.split(fields[1])
            if tokens and Path(tokens[0]).name.startswith('python') and any(
                Path(token).name in {'test_native_desktop.py', 'test_native_performance.py'} for token in tokens[1:]
            ):
                raise RuntimeError('Another native acceptance harness is active; do not run competing test windows')
    script = output/'native-performance-injected.js'
    config = {'remote':'performance-delayed', 'delayMs':delay_seconds*1000, 'expectedVersion':version}
    script.write_text('window.__FLEET_PERFORMANCE_CONFIG__='+json.dumps(config)+';\n'+(ROOT/'tests/native_performance.js').read_text())
    report = output/'native-performance-report.json'
    env = os.environ.copy()
    env.update(AGENT_FLEET_TEST_SCRIPT=str(script), AGENT_FLEET_TEST_REPORT=str(report),
               CODEX_HOME=str(local_home/'absent-codex'), CLAUDE_CONFIG_DIR=str(local_home/'absent-claude'))
    with (output/'native-app.log').open('w') as log:
        app = subprocess.Popen([str(desktop), '--home', str(local_home)], env=env,
                               stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
        awake = subprocess.Popen(['/usr/bin/caffeinate', '-d', '-i', '-w', str(app.pid)],
                                 stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        try:
            code = app.wait(timeout=75)
            if not report.is_file():
                raise RuntimeError('Native app exited without a performance report')
            data = json.loads(report.read_text())
            data['binary_sha256'] = sha256(desktop)
            data['session_before'] = session
            data['session_after'] = json.loads(run(['/usr/bin/swift', str(ROOT/'scripts/macos_gui_state.swift')], timeout=20))
            if data['session_after']['screen_locked'] or not data['session_after']['console_session']:
                data.update(passed=False, unavailable='macOS session became unavailable during measurement')
                return data, 77
            return data, 0 if code == 0 and data.get('passed') else 1
        finally:
            if app.poll() is None:
                app.terminate()
                try: app.wait(timeout=5)
                except subprocess.TimeoutExpired: app.kill(); app.wait(timeout=5)
            awake.terminate()
            awake.wait(timeout=5)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--remote', required=True, help='Existing explicit client connection; no implicit default')
    parser.add_argument('--cli', type=Path, default=Path(shutil.which('agent-fleet') or 'agent-fleet'))
    parser.add_argument('--desktop', type=Path, help='Built debug desktop with custom-protocol')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--samples', type=int, default=20)
    parser.add_argument('--delay-seconds', type=float, default=2)
    parser.add_argument('--ssh-only', action='store_true', help='Only the SSH gate; never claims a native UI pass')
    args = parser.parse_args()
    if not 20 <= args.samples <= 100 or not math.isfinite(args.delay_seconds) or not 2 <= args.delay_seconds <= 5:
        parser.error('Use 20 to 100 status samples and a real delay between 2 and 5 seconds')
    if not args.ssh_only and (not args.desktop or not args.desktop.is_file()):
        parser.error('Pass --desktop for native UI acceptance or explicitly select --ssh-only')
    cli = args.cli.resolve()
    if not cli.is_file():
        parser.error('Select an installed native CLI with --cli')
    if not args.ssh_only and b'AGENT_FLEET_TEST_SCRIPT' not in args.desktop.read_bytes():
        parser.error('Native UI acceptance requires the debug-only hook, not a release desktop')
    args.output.mkdir(mode=0o700, parents=True, exist_ok=False)
    result = {'recorded_at':datetime.now(timezone.utc).isoformat(),
              'harness_git_base':run(['git','-C',str(ROOT),'rev-parse','HEAD']).strip(),
              'harness_sha256':sha256(__file__),
              'native_script_sha256':sha256(ROOT/'tests/native_performance.js'),
              'platform':platform.platform(), 'architecture':platform.machine(),
              'connection':args.remote, 'cli_sha256':sha256(cli),
              'production_mutations':False, 'provider_inference':False}
    exit_code = 1
    try:
        version = run([str(cli), '--version']).strip()
        result['version'] = version
        config = connection(cli, args.remote)
        result['remote_platform'] = ssh(config['host'], ['uname','-sm']).strip()
        result['remote_binary'] = json.loads(ssh(config['host'], ['python3','-c',
            'import hashlib,json,pathlib,shutil,subprocess,sys; c=sys.argv[1]; p=pathlib.Path(shutil.which(c) or c); '
            'print(json.dumps({"sha256":hashlib.sha256(p.read_bytes()).hexdigest(),"version":subprocess.check_output([str(p),"--version"],text=True).strip()}))', config['command']]))
        reference = json.loads((ROOT/'docs/rust-tauri-validation.json').read_text())
        result['application_reviewed_commit'] = reference['reviewed_implementation_commit']
        result['cli_matches_reference_release'] = result['cli_sha256'] == reference['release']['mac_cli_sha256']
        result['remote_matches_reference_release'] = result['remote_binary']['sha256'] == reference['release']['linux_cli_sha256']
        if args.desktop:
            result['desktop_matches_reference_debug'] = sha256(args.desktop) == reference['native_gui']['debug_binary_sha256']
        with tempfile.TemporaryDirectory(prefix='fleet-native-performance-') as tmp:
            local_home = Path(tmp)/'pool'
            local_home.mkdir(mode=0o700)
            add_connection(cli, local_home, 'measured', config)
            result['ssh'] = cached_status(cli, local_home, 'measured', args.samples)
            if args.ssh_only:
                result['native_ui'] = {'passed':False, 'not_requested':True}
                exit_code = 0 if result['ssh']['passed'] else 1
            else:
                with delayed_endpoint(config, args.delay_seconds) as (slow, folder):
                    add_connection(cli, local_home, 'performance-delayed', slow)
                    result['native_ui'], exit_code = native_ui(args.desktop.resolve(), local_home,
                        args.output, args.delay_seconds, version)
                    raw = ssh(config['host'], ['python3','-c',
                        'import json,pathlib,sys; p=pathlib.Path(sys.argv[1])/"timings.jsonl"; '
                        'print(json.dumps([json.loads(line) for line in p.read_text().splitlines()] if p.exists() else []))', folder])
                    result['remote_delay_observations'] = json.loads(raw)
                    if result['native_ui'].get('passed') and (len(result['remote_delay_observations']) != 3 or
                        any(row['delay_ms'] < args.delay_seconds*1000 or row['returncode'] != 0 for row in result['remote_delay_observations'])):
                        raise RuntimeError('The real remote delay was not proven for all three requests')
                    exit_code = exit_code or (0 if result['ssh']['passed'] else 1)
        result['requested_gates_passed'] = exit_code == 0
        result['all_gates_passed'] = result['ssh']['passed'] and bool(result['native_ui'].get('passed'))
    except Exception as error:
        result.update(requested_gates_passed=False, all_gates_passed=False,
                      error=f'{type(error).__name__}: {error}')
        exit_code = 1
    finally:
        (args.output/'performance.json').write_text(json.dumps(result, indent=2, ensure_ascii=False)+'\n')
    print(args.output/'performance.json')
    return exit_code


if __name__ == '__main__':
    raise SystemExit(main())
